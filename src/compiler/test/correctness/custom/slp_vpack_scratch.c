	A[8 + 0] = B[8 + 0] + C[8 + 0];
	A[8 + 1] = B[8 + 1] + C[8 + 1];
	A[8 + 2] = B[8 + 2] + C[8 + 2];
	A[8 + 3] = B[8 + 3] + C[8 + 3];
	{
		T s0 = B[0], s1 = B[1], s2 = B[2], s3 = B[3];
		A[0] = s0 & C[0];
		A[1] = s0 ^ C[1];
		A[2] = s0 * C[2];
		A[3] = s0 & C[3];
		A[4 + 0] = s1 ^ C[4 + 0];
		A[4 + 1] = s1 - C[4 + 1];
		A[4 + 2] = s1 | C[4 + 2];
		A[8 + 0] = s2 + C[8 + 0];
		A[12 + 3] = s3 ^ C[12 + 3];
	}
